"""Generates and runs ``validation/matlab/ref_examples.m``: RISE solves each case in ``examples_config.CONFIG``.

Output: ``validation/ref/examples.mat`` with, for each case: retcode, driver parameters (``p_in_json``),
final parameters, steady state, Q, stability and IRFs by regime (unit shock, 10 periods).
Usage: ``.venv/bin/python validation/gen_ref_examples.py [filter]`` (with a filter, only the selected cases are rewritten).
"""
import subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from examples_config import CONFIG, FOLDER

here = Path(__file__).parent
pat = sys.argv[1] if len(sys.argv) > 1 else ""
q = lambda s: s.replace("'", "''")
lines = ["% Generated by validation/gen_ref_examples.py; do not edit by hand.",
         "rise_root = getenv('RISE_TOOLBOX'); if isempty(rise_root), rise_root = fullfile(getenv('HOME'),'RISE_toolbox'); end",
         "addpath(rise_root); rise_startup(); here=pwd;",
         "outfile=fullfile(here,'..','ref','examples.mat'); out=struct();",
         "if exist(outfile,'file'), out=load(outfile); end"]
for rel, variants in CONFIG.items():
    for v in variants:
        if pat in v["key"] or pat in rel:
            lines.append(f"out.{v['key']}=runcase('{FOLDER[v['key']]}','{q(v['matlab'])}',{{{v.get('msolve', '')}}});")
lines += ["cd(here); save(outfile,'-struct','out','-v7'); disp('OK');", "",
"""function r=runcase(folder,code,sopts)
  r=struct('retcode',-1); here=pwd; work=tempname; mkdir(work);
  rise_root = getenv('RISE_TOOLBOX'); if isempty(rise_root), rise_root = fullfile(getenv('HOME'),'RISE_toolbox'); end
  copyfile(fullfile(rise_root,'examples',folder,'*'),work); cd(work);
  try
    p_in=struct(); evalc(code);
    if iscell(p_in), p_in=cell2struct(p_in(:,2),p_in(:,1),1); end
    r.p_in_json=jsonencode(p_in);
    if ~isempty(fieldnames(p_in)), m=set(m,'parameters',p_in); end
    [~,m,rc]=evalc('solve(m,sopts{:})'); r.retcode=rc;
    if rc==0
      sol=m.solution; r.endo={m.endogenous.name}; r.exo={m.exogenous.name};
      r.ss=cell2mat(cellfun(@full,sol.ss,'uni',0)); r.Q=full(sol.transition_matrices.Q);
      r.stable=is_stable_system(m);
      par=get(m,'parameters'); r.par_names=fieldnames(par); r.par_values=cell2mat(struct2cell(par));
      ii=irf(m,'irf_periods',10,'irf_regime_specific',true,'irf_shock_sign',1); sh=fieldnames(ii);
      for a=1:numel(sh), vn=fieldnames(ii.(sh{a}));
        for b=1:numel(vn), r.(['irf__' sh{a} '__' vn{b}])=double(ii.(sh{a}).(vn{b})); end, end
    else
      r.message=decipher(rc);
    end
  catch err, r.error=getReport(err,'basic'); end
  cd(here); fprintf('%s: retcode %d\\n',folder,r.retcode);
end

function p=stata_params(file)
  % prior starting values and fixed parameters set in the driver
  txt=fileread(file); p=struct(); priors=struct();
  tok=regexp(txt,'p=\\{(.*?)\\};','tokens','once');
  if ~isempty(tok), c=eval(['{' tok{1} '}']); for k=1:size(c,1), p.(c{k,1})=c{k,2}; end, end
  tok=regexp(txt,'set\\(m,''parameters'',\\{''(\\w+)'',([\\d.]+)\\}\\)','tokens');
  for k=1:numel(tok), p.(tok{k}{1})=str2double(tok{k}{2}); end
  L=regexp(txt,'priors\\.\\w+\\s*=\\s*\\{[^}]*\\};','match');
  for k=1:numel(L), eval(L{k}); end
  f=fieldnames(priors);
  for k=1:numel(f), if ~isfield(p,f{k}), p.(f{k})=priors.(f{k}){1}; end, end
end
"""]
(here / "matlab" / "ref_examples.m").write_text("\n".join(lines))
print(f"{sum(1 for l in lines if l.startswith('out.') )} cases")
subprocess.run(["/Applications/MATLAB_R2024a.app/bin/matlab", "-batch", "ref_examples"], cwd=here / "matlab", check=False)
