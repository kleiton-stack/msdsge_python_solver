"""Sweeps the models of the RISE examples: converts, builds, solves and compares with RISE.

The macro flags, parameters and options set by the MATLAB scripts of each example
(``howto.m``, ``driver*.m``, ``master*.m``) are in ``validation/examples_config.py``. When a RISE
reference exists (``validation/ref/examples.mat``, generated by ``gen_ref_examples.py``), the line
reports the largest steady-state and IRF differences (unit shock, 10 periods, by regime).
Usage: ``.venv/bin/python validation/sweep_examples.py [filter] > validation/ref/sweep_examples.txt``.
"""
import collections, os, signal, sys, warnings
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
from msdsge import Model
from msdsge.convert import rs_to_mod
from examples_config import CONFIG, FRAGMENTS, parameters_of, reference, tabulated_steady_state
from examples_ssfiles import FILES
warnings.filterwarnings("ignore")
root = Path(os.environ.get("RISE_TOOLBOX", Path.home() / "RISE_toolbox")) / "examples"


class Timeout(Exception):
    pass


def handler(*a):
    raise Timeout()


def build(rel, cfg):
    """Converts and builds the model of one case; returns (model, solve options)."""
    key = cfg.get("key")
    text = rs_to_mod(root / rel, flags=cfg.get("flags"), parameters=parameters_of(key) if key else None)
    m = Model.from_text(text)
    opts = dict(cfg.get("solve", {}))
    how = cfg.get("ss", "")
    if how.startswith("py:"):
        m.steady_state_file = FILES[how[3:]]
    elif how == "tab":
        m.steady_state_file = tabulated_steady_state(key)
        if m.steady_state_file is None:
            raise RuntimeError("no RISE reference to tabulate the steady state of the .m file")
    if "steady_state_imposed" in opts:
        m.steady_state_imposed = opts.pop("steady_state_imposed")
    return m, opts


def compare(s, ref, log_vars=()):
    """(largest steady-state difference, largest IRF difference, where, scale) against RISE.

    ``log_vars``: variables that the solution stores in logs (RISE stores the steady state in levels).
    """
    m = s.model
    if log_vars:
        import copy
        s = copy.copy(s)
        s.ss = s.ss.copy()
        idx = [m.endogenous.index(v) for v in log_vars]
        s.ss[:, idx] = np.exp(s.ss[:, idx])
    endo = [str(x) for x in np.atleast_1d(ref.endo)]
    rss = np.asarray(ref.ss, float).reshape(len(endo), -1)
    dss = max(abs(s.ss[r, m.endogenous.index(v)] - rss[i, r]) for i, v in enumerate(endo) if v in m.endogenous
              for r in range(m.h))
    irf = s.irf(periods=10, size=1.0)
    worst, where, scale = 0.0, "", 0.0
    for f in ref._fieldnames:
        if not f.startswith("irf__"):
            continue
        _, sh, v = f.split("__")
        if v not in irf.columns or sh not in m.exogenous:
            continue
        z = np.asarray(getattr(ref, f), float).reshape(11, -1)[1:]
        for r in range(m.h):
            d = np.max(np.abs(irf.loc[(sh, r + 1), v].to_numpy() - z[:, r]))
            scale = max(scale, np.max(np.abs(z[:, r])))
            if d > worst:
                worst, where = d, f"{sh}->{v} r{r + 1}"
    return dss, worst, where, scale


if __name__ == "__main__":
    signal.signal(signal.SIGALRM, handler)
    res = collections.defaultdict(list)
    pat = sys.argv[1] if len(sys.argv) > 1 else ""
    files = sorted(root.rglob("*.rs")) + sorted(root.rglob("*.rz"))
    nfiles, okfiles = 0, set()
    for f in files:
        rel = str(f.relative_to(root))
        if pat not in rel:
            continue
        nfiles += 1
        if rel in FRAGMENTS:
            res["fragment or file without calibration (not a complete model)"].append((rel, FRAGMENTS[rel]))
            continue
        for cfg in CONFIG.get(rel) or [{}]:
            tag = rel + (f" [{cfg['label']}]" if cfg.get("label") else "")
            stage = "convert"
            signal.alarm(180)
            try:
                m, opts = build(rel, cfg); stage = "calibration"
                p = m.parameter_values(); stage = "solution"
                try:
                    s = m.solve(**opts); how = opts.get("solver", "mfi")
                except Exception as e:
                    if "solver" in opts or "steady state" in str(e).lower():
                        if "steady state" in str(e).lower():
                            stage = "steady state"
                        raise
                    s = m.solve(solver="mnk", **opts); how = "mnk (mfi failed)"
                stage = "ok"
                msg = f"n={m.n} h={m.h} {how} radius={s.mss_radius:.4f}"
                ref = reference(cfg["key"]) if cfg.get("key") else None
                if ref is not None and getattr(ref, "retcode", 1) == 0 and "solve_occbin" in cfg.get("msolve", "") + cfg["matlab"]:
                    msg += " | reference regime only; the comparison with RISE is the one in msdsge.occbin"
                elif ref is not None and getattr(ref, "retcode", 1) == 0:
                    dss, dirf, where, scale = compare(s, ref, opts.get("log_vars", ()))
                    msg += f" | RISE: ss diff {dss:.1e}, IRF diff {dirf:.1e} (scale {scale:.1e}) {where}"
                elif ref is not None:
                    why = " ".join(str(getattr(ref, "message", getattr(ref, "error", ""))).split())
                    msg += f" | RISE did not solve: {why[:90]}"
                res["ok" + ("" if s.is_stable else " (not MSS)")].append((tag, msg))
                okfiles.add(rel)
            except Timeout:
                res[f"{stage}: timed out"].append((tag, ""))
            except Exception as e:
                res[stage].append((tag, f"{type(e).__name__}: {str(e)[:150]}"))
            finally:
                signal.alarm(0)
    tot = sum(len(v) for v in res.values())
    print(f"{nfiles} model files, {tot} cases (a file may have more than one variant); "
          f"{len(okfiles)} files with at least one case solved")
    for k, v in sorted(res.items(), key=lambda kv: -len(kv[1])):
        print(f"\n== {k}: {len(v)} of {tot} cases")
        for rel, msg in v:
            print(f"   {rel}  {msg}")
