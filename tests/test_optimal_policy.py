"""Optimal policy: commitment, discretion, loose commitment and optimal simple rules.

RISE references (commit 1b2edfa) in ``validation/ref/optimal_policy.mat``, generated by
``validation/matlab/ref_optimal_policy.m``. The converted models are in
``validation/optimal_policy`` (``validation/gen_optimal_policy_mods.py``).
"""
from pathlib import Path

import numpy as np
import pandas as pd
import pytest
import scipy.io as sio

from msdsge import Model, ModelSyntaxError, load
from msdsge.convert import rs_to_mod
from msdsge.optimal_policy import loss, optimal_simple_rule, solve_optimal_policy

ROOT = Path(__file__).parents[1]
MODS = ROOT / "validation" / "optimal_policy"
_REF = {}


def ref(case):
    if not _REF:
        _REF.update(sio.loadmat(ROOT / "validation" / "ref" / "optimal_policy.mat", squeeze_me=True, struct_as_record=False))
    return _REF[case]


def _dense(x):
    return np.asarray(x.todense() if hasattr(x, "todense") else x, float)


def tz_diff(sol, r, regmap=None, rise_regimes=None, flip=()):
    """Largest difference between [T, 0, R] of the solution and RISE's Tz, in the variables with the same name.

    Rows of Tz: alphabetical order of RISE's endogenous variables; columns: states in ``order_var``
    order, sigma and shocks. ``regmap[k]`` is the regime of the solution (0-based) that corresponds
    to RISE regime k. ``flip``: multipliers with the opposite sign (the sign follows the
    normalisation of the equation).
    """
    endo = list(r.endo)
    order = np.asarray(r.order_var, int) - 1
    states = set(np.atleast_1d(r.state_names))
    cols = [endo[i] for i in order if endo[i] in states]
    mine = sol.model.endogenous
    rows = [v for v in endo if v in mine]
    ccom = [c for c in cols if c in mine]
    exo = [list(np.atleast_1d(r.exo)).index(e) for e in sol.model.exogenous]
    Tz = list(r.Tz) if getattr(r.Tz, "dtype", None) == object else [r.Tz]   # one regime: bare matrix
    worst = 0.0
    for k in (range(len(Tz)) if rise_regimes is None else rise_regimes):
        a = k if regmap is None else regmap[k]
        Z = _dense(Tz[k])
        ri, mi = [endo.index(v) for v in rows], [mine.index(v) for v in rows]
        T_rise = Z[ri][:, [cols.index(c) for c in ccom]]
        R_rise = Z[ri][:, len(cols) + 1:][:, exo]
        sr = np.array([-1.0 if v in flip else 1.0 for v in rows])[:, None]
        sc = np.array([-1.0 if c in flip else 1.0 for c in ccom])[None, :]
        worst = max(worst, np.max(np.abs(sr * sol.T[a][mi][:, [mine.index(c) for c in ccom]] * sc - T_rise)),
                    np.max(np.abs(sr * sol.R[a][mi] - R_rise)))
        # state columns that RISE does not have under the same name cannot be compared here
    return worst, len(rows), len(ccom)


NK = """
var pi x u; varexo e; parameters beta kappa alpha rho gam;
beta = 0.99; kappa = 0.1; alpha = 0.25; rho = 0.5; gam = 1;
model;
  pi = beta*pi(+1) + kappa*x + u;
  u = rho*u(-1) + e;
end;
planner_objective(discount=beta, commitment=gam);
  -0.5*(pi^2 + alpha*x^2);
end;
"""


# ------------------------------------------------------------------ syntax
def test_parser_block():
    m = Model.from_text(NK)
    pl = m.spec.planner
    assert str(pl["discount"]) == "beta" and str(pl["commitment"]) == "gam"
    assert len(m.spec.equations) == 2 and len(m.spec.endogenous) == 3
    # without commitment the block is the objective of a simple rule and the model must be square
    with pytest.raises(ModelSyntaxError):
        Model.from_text(NK.replace("planner_objective(discount=beta, commitment=gam);", "planner_objective;"))
    with pytest.raises(ModelSyntaxError):
        Model.from_text(NK.replace("commitment=gam", "commitment=gam, other=1"))
    # with commitment, a square model (rule not removed) is an error
    with pytest.raises(ModelSyntaxError):
        Model.from_text(NK.replace("u = rho*u(-1) + e;", "u = rho*u(-1) + e; x = 0.5*pi;"))


def test_convert_block(tmp_path):
    rs = tmp_path / "m.rs"
    rs.write_text("""endogenous PAI, Y, I
exogenous E
parameters a, g
model
   PAI = a*PAI(+1) + 0.1*Y + E;
   Y = Y(+1) - (I - PAI(+1));
planner_objective{discount = 0.99,commitment=g} -.5*(PAI^2+.6*Y^2);
parameterization
   a, 0.9;
   g, 0.5;
""")
    text = rs_to_mod(rs)
    assert "planner_objective(discount = 0.99, commitment=g);" in text
    s = Model.from_text(text).solve()
    assert s.solver == "policy-loose" and s.T.shape[0] == 2
    rs.write_text(rs.read_text().replace("{discount = 0.99,commitment=g}", "").replace(
        "Y = Y(+1) - (I - PAI(+1));", "Y = Y(+1) - (I - PAI(+1));\n   I = 1.5*PAI;"))
    text = rs_to_mod(rs)
    assert "planner_objective;" in text and Model.from_text(text).spec.planner["commitment"] is None


# ------------------------------------------------------------------ canonical NK (closed-form solution)
def test_nk_discretion_closed_form():
    """Clarida, Galí and Gertler (1999): x = -kappa/(kappa^2 + alpha(1-beta rho)) u, pi = alpha/(...) u."""
    b, k, a, rho = 0.99, 0.1, 0.25, 0.5
    s = Model.from_text(NK).solve({"gam": 0})
    den = k * k + a * (1 - b * rho)
    assert s.solver == "policy-discretion"
    assert s.R[0][:3, 0] == pytest.approx([a / den, -k / den, 1.0], abs=1e-11)
    assert s.T[0][:2, 2] == pytest.approx([rho * a / den, -rho * k / den], abs=1e-11)
    assert np.all(s.T[0][:, 3:] == 0)       # lagged multipliers are not states


def test_nk_commitment_closed_form():
    """Under commitment: pi_t = -(alpha/kappa)(x_t - x_{t-1}) and x_t = delta x_{t-1} - kappa delta/(alpha(1 - delta beta rho)) u_t."""
    b, k, a, rho, n = 0.99, 0.1, 0.25, 0.5, 40
    s = Model.from_text(NK).solve({"gam": 1})
    irf = s.irf("e", periods=n)
    aa = a / (a * (1 + b) + k * k)
    d = (1 - np.sqrt(1 - 4 * b * aa * aa)) / (2 * aa * b)
    x, last = np.zeros(n), 0.0
    for t in range(n):
        x[t] = last = d * last - k * d / (a * (1 - d * b * rho)) * rho ** t
    pi = -(a / k) * (x - np.r_[0.0, x[:-1]])
    assert irf["x"].to_numpy() == pytest.approx(x, abs=1e-10)
    assert irf["pi"].to_numpy() == pytest.approx(pi, abs=1e-10)
    assert s.model.endogenous[3:] == ["MULT_1", "MULT_2"]


def test_nk_loose_commitment_between_extremes():
    """Welfare increases with the commitment probability; the 'redone' regime ignores the multipliers."""
    m = Model.from_text(NK)
    w = []
    for g in (0.0, 0.25, 0.5, 0.75, 1.0):
        s = m.solve({"gam": g})
        w.append(loss(s).unconditional)
        if 0 < g < 1:
            assert s.model.chain_names == ["loosecommit"] and s.Q == pytest.approx(np.array([[g, 1 - g], [g, 1 - g]]))
            assert np.all(s.T[1][:, 3:] == 0) and s.T[1][:, :3] == pytest.approx(s.T[0][:, :3])
            assert np.any(s.T[0][:, 3:] != 0)
            assert s.residual < 1e-10
    assert np.all(np.diff(w) > 0)
    # limits: gamma -> 0 and gamma -> 1 reproduce discretion and commitment
    d, c = m.solve({"gam": 0}), m.solve({"gam": 1})
    assert m.solve({"gam": 1e-9}).R[0] == pytest.approx(d.R[0], abs=1e-7)
    assert m.solve({"gam": 1 - 1e-9}).T[0] == pytest.approx(c.T[0], abs=1e-6)


def test_solution_is_a_regular_solution():
    """IRFs, simulation and filter work with the optimal-policy solution."""
    text = NK.replace("var pi x u;", "var pi x u i; varobs pi i;").replace("varexo e;", "varexo e v;").replace(
        "u = rho*u(-1) + e;", "u = rho*u(-1) + e; x = x(+1) - (i - pi(+1)) + v;")
    s = Model.from_text(text).solve({"gam": 0.5})
    sim = s.simulate(periods=120, seed=3)
    assert set(sim["regime"]) == {1, 2} and {"MULT_1", "MULT_2", "MULT_3"} <= set(sim.columns)
    f = s.filter(sim[["pi", "i"]])
    assert np.isfinite(f.loglik)
    assert f.smoothed_probs.shape == (120, 2)
    assert s.irf("e", periods=5, regime=2).shape[0] == 5
    # the likelihood distinguishes the degree of commitment that generated the data
    ll = {g: Model.from_text(text).solve({"gam": g}).filter(sim[["pi", "i"]]).loglik for g in (0.0, 0.5, 1.0)}
    assert ll[0.5] > ll[0.0]


def test_conditional_loss_matches_simulation():
    """v(x0, r) matches the average of discounted simulations (Monte Carlo)."""
    s = Model.from_text(NK).solve({"gam": 0.6})
    L = loss(s, x0={"u": 1.0}, regime=2)
    assert L.conditional == pytest.approx(np.array([1.0 if v == "u" else 0 for v in s.model.endogenous])
                                          @ L.V[1] @ np.array([1.0 if v == "u" else 0 for v in s.model.endogenous]) + L.d[1])
    rng = np.random.default_rng(0)
    W, beta, n = s.planner.W[0] / 2, 0.99, s.T.shape[1]
    reps, horizon, tot = 2000, 500, 0.0
    x = np.zeros((reps, n))
    x[:, s.model.endogenous.index("u")] = 1.0
    disc = 1.0
    tot = np.einsum("ri,ij,rj->r", x, W, x).copy()
    for _ in range(horizon):
        reg = (rng.random(reps) > 0.6).astype(int)
        e = rng.standard_normal((reps, 1))
        x = np.einsum("rij,rj->ri", s.T[reg], x) + np.einsum("rij,rj->ri", s.R[reg], e)
        disc *= beta
        tot += disc * np.einsum("ri,ij,rj->r", x, W, x)
    tail = disc * beta / (1 - beta) * L.expected_period       # remainder of the sum, at the stationary value
    assert tot.mean() + tail == pytest.approx(L.conditional, rel=0.03)


def test_requirements():
    with pytest.raises(NotImplementedError):   # nonlinear model
        Model.from_text(NK.replace("kappa*x + u", "kappa*x^2 + u")).solve()
    with pytest.raises(NotImplementedError):   # non-quadratic objective
        Model.from_text(NK.replace("alpha*x^2", "alpha*x^4")).solve()
    with pytest.raises(NotImplementedError):   # nonzero gradient: distorted steady state
        Model.from_text(NK.replace("alpha*x^2", "alpha*(x-1)^2")).solve()


# ------------------------------------------------------------------ against RISE
# RISE regimes in Canonical: (loosecommit, vol) = (1,1), (1,2), (2,1), (2,2); always 4, even with
# commitment 0 or 1. Here the pure cases have only the regimes of the model.
_PURE = {0.0: dict(regmap=[0, 1, 0, 1]), 0.5: {}, 1.0: dict(rise_regimes=[0, 1])}


@pytest.mark.parametrize("case,gam", [("can_d", 0.0), ("can_l", 0.5), ("can_c", 1.0)])
def test_canonical_matches_rise(case, gam):
    """StochasticReplanning/Canonical.rs: T, R (variables and multipliers), Q and stability."""
    r = ref(case)
    s = load(MODS / "canonical.mod").solve({"commit_prob": gam})
    diff, nrows, ncols = tz_diff(s, r, **_PURE[gam])
    assert nrows == 15 and ncols == 10          # 8 variables + 7 multipliers; 10 states
    assert diff < 1e-8                          # tolerance of the RISE iteration (1.5e-8)
    assert s.is_stable == bool(r.stable)
    if gam == 0.5:
        assert s.Q == pytest.approx(_dense(r.Q), abs=1e-12)
        assert s.model.regimes == [(1, 1), (1, 2), (2, 1), (2, 2)]


def test_canonical_irf_matches_rise():
    r = ref("can_l")
    s = load(MODS / "canonical.mod").solve({"commit_prob": 0.5})
    irf = s.irf(periods=20)
    for shock in s.model.exogenous:
        for v in ("PAI", "Y", "I", "R"):
            mine = irf.loc[shock][v].unstack(0).to_numpy()          # (period, regime)
            assert mine == pytest.approx(getattr(r, f"irf__{shock}__{v}")[1:], abs=1e-8)   # row 0 of RISE is the initial point


@pytest.mark.parametrize("case,gam", [("canL_d", 0.0), ("canL_l", 0.5), ("canL_c", 1.0)])
def test_switching_lead_coefficient_matches_rise_timing(case, gam):
    """Lead coefficient switching regime: RISE uses the matrices of the current regime (timing='rise')."""
    m = load(MODS / "op_canL.mod")
    p = m.parameter_values({"commit_prob": gam})
    s = solve_optimal_policy(m, p, timing="rise")
    assert tz_diff(s, ref(case), **_PURE[gam])[0] < 1e-8
    e = solve_optimal_policy(m, p, timing="exact")
    iy = slice(0, m.n)
    if gam == 0:    # without a lagged multiplier the two conventions coincide
        assert e.T[:, iy, iy] == pytest.approx(s.T[:, iy, iy], abs=1e-10)
    else:           # with exact dating the plan is better (it is the optimum of the problem with switching)
        assert "MULTLAG_PAI" in e.model.endogenous
        assert np.max(np.abs(e.T[:, iy, iy] - s.T[:, iy, iy])) > 1e-3
        assert loss(e).unconditional > loss(s).unconditional
        # evaluated at the initial conditions of the plan (zero multipliers), in each regime
        x0 = {"ZPAI": 1.0}
        for reg in (1, 2):
            assert loss(e, x0=x0, regime=reg).conditional >= loss(s, x0=x0, regime=reg).conditional - 1e-9


def test_switching_commitment_probability():
    """Commitment probability per regime: Q = Q_model x [gamma_s, 1 - gamma_s].

    RISE (2019) builds another matrix (probability of keeping the plan 0.55 starting from 'kept' and
    0.30 starting from 'redone', regardless of the volatility regime), which is not reproduced.
    """
    s = load(MODS / "op_canG.mod").solve()
    Qv = np.array([[0.9, 0.1], [0.1, 0.9]])
    g = np.array([0.3, 0.8])
    expected = np.block([[Qv * g[:, None], Qv * (1 - g)[:, None]]] * 2)
    assert s.Q == pytest.approx(expected, abs=1e-12)
    assert s.residual < 1e-9 and s.is_stable
    rise_Q = _dense(ref("canG").Q)
    assert rise_Q[0, :2].sum() == pytest.approx(0.55) and rise_Q[2, :2].sum() == pytest.approx(0.30)


# ------------------------------------------------------------------ optimal simple rule
def test_osr_loss_matches_rise():
    """OptimalSimpleRules/Canonical_osr.rs: solution and loss() at the initial point (RISE uses W, not W/2)."""
    r = ref("osr")
    s = load(MODS / "canonical_osr.mod").solve()
    assert tz_diff(s, r)[0] < 1e-8
    L = loss(s, rise_scale=True)
    assert L.unconditional == pytest.approx(float(r.loss_welf), rel=1e-9)
    assert L.d[0] == pytest.approx(float(_dense(r.loss_d).ravel()[0]), rel=1e-9)
    endo = list(r.endo)
    idx = [endo.index(v) for v in ("DI", "I", "PAI", "R", "Y")]
    mine = [s.model.endogenous.index(v) for v in ("DI", "I", "PAI", "R", "Y")]
    assert L.V[0][np.ix_(mine, mine)] == pytest.approx(_dense(r.loss_V)[np.ix_(idx, idx)], abs=1e-6)
    assert loss(s).unconditional == pytest.approx(L.unconditional / 2)


def test_osr_optimum_matches_rise():
    """RISE's estimate() on a model with planner_objective without commitment maximises welfare."""
    o = ref("osr_opt")
    res = optimal_simple_rule(load(MODS / "canonical_osr.mod"))
    assert res.names == ["gam_lag", "gam_y"] and res.success
    assert 2 * res.welfare == pytest.approx(float(o.loss_welf), rel=1e-7)      # -338.5147
    assert 2 * res.welfare0 == pytest.approx(-float(o.f0) - float(o.log_prior), rel=1e-9)
    assert res.x == pytest.approx(np.ravel(o.mode), rel=2e-3)                   # shallow optimum in gam_y
    assert res.welfare > res.welfare0


