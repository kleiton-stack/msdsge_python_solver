def ref2(case):
    """fm95_ms_lc.rs and Canonical_plain.rs: the local RISE does not accept ``model(linear)``; the
    reference was generated replacing it by ``model`` (validation/matlab/ref_optimal_policy2.m)."""
    if "2" not in _REF:
        _REF["2"] = sio.loadmat(ROOT / "validation" / "ref" / "optimal_policy2.mat", squeeze_me=True, struct_as_record=False)
    return _REF["2"][case]


@pytest.mark.parametrize("case,gam", [("fm95_c", 1.0), ("fm95_l", 0.5), ("fm95_d", 0.0)])
def test_fuhrer_moore_irf_matches_rise(case, gam):
    """Fuhrer-Moore (1995) with leads and lags up to 3: IRFs under commitment, loose and discretion.

    The comparison is by IRFs because the numbering of the multipliers and the names of the auxiliaries differ.
    """
    r = ref2(case)
    m = load(MODS / "fm95.mod")
    s = solve_optimal_policy(m, commitment=gam)
    assert s.residual < 1e-8
    irf = s.irf(periods=20, regime=1)
    for shock in m.exogenous:
        for v in ("Y", "RHO", "I", "PAI", "W", "P", "V", "WBAR", "DI"):
            a = np.asarray(getattr(r, f"irf__{shock}__{v}"), float)
            a = a if a.ndim == 1 else a[:, 0]
            assert irf.loc[shock][v].to_numpy() == pytest.approx(a[1:], abs=1e-8)


