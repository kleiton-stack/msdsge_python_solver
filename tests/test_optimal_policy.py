# ------------------------------------------------------------------ Smets-Wouters
_SW = {"sw_d": ("usmodel_ms_lc", {"ProbabilityOfCommitment": 0.0}, dict(regmap=[0, 0])),
       "sw_l": ("usmodel_ms_lc", {"ProbabilityOfCommitment": 0.5}, {}),
       "sw_c": ("usmodel_ms_lc", {"ProbabilityOfCommitment": 1.0}, dict(rise_regimes=[0])),
       # MULT_24 is the multiplier of "pinf_target = pinf + ms", which RISE normalises with the opposite sign
       "swsr": ("usmodel_sr_switch", {}, dict(flip=("MULT_24",)))}


@pytest.mark.parametrize("case", list(_SW))
def test_smets_wouters_matches_rise(case):
    """usmodel_ms_lc.rs and usmodel_sr_switch.rs (40 variables, 33 to 37 multipliers)."""
    try:
        r = ref(case)
    except KeyError:
        pytest.skip(f"reference '{case}' was not generated (RISE takes 15 minutes to hours per case)")
    if getattr(r, "retcode", 1) != 0:
        pytest.skip(f"RISE did not solve '{case}': {getattr(r, 'error', getattr(r, 'retcode', ''))}")
    name, pars, kw = _SW[case]
    s = load(MODS / f"{name}.mod").solve(pars)
    diff, nrows, _ = tz_diff(s, r, **kw)
    assert nrows >= 70
    assert diff < 1e-4          # the RISE iteration stops at a change of 1.5e-8, with slow convergence
    assert s.is_stable == bool(r.stable)
