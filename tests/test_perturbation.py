@pytest.mark.parametrize("name", ["o2c", "o2", "small_nk", "frwz_nk"])
def test_orders_1_to_3_match_rise(name):
    """Tz, Tzz and Tzzz equal to those of RISE (relative tolerance: RISE's mfi stops at 1.5e-8)."""
    ref = _ref("pert.mat", name)
    s = _solved(name, 3)
    for j in (1, 2, 3):
        mine, rise = _mine_and_rise(s.model, s.pert, ref, j)
        assert np.abs(mine - rise).max() < 5e-7 * max(1.0, np.abs(rise).max())


def test_second_order_equals_order2_module():
    from msdsge.order2 import solve_second_order
    s = _solved("o2", 3)
    assert s.pert.tensor(2) == pytest.approx(solve_second_order(s), abs=1e-12)


def test_orders_4_and_5_analytic_derivatives():
    """A = A(-1)^rho exp(sig E) has closed-form derivatives; the package reproduces them up to 5th order.

    RISE (commit 1b2edfa) does not: its Tzzzz and Tzzzzz differ from the analytic value. Recorded here.
    """
    s = _solved("o2c", 5)
    m = s.model
    iA = m.endogenous.index("A")
    a = [m.endogenous[i] for i in s.pert.states].index("A")
    e = s.pert.states.size + 1
    rho, sig = 0.9, 0.02
    fall = lambda j: float(np.prod([rho - i for i in range(j)]))      # j-th derivative of A(-1)^rho at 1
    for j in (2, 3, 4, 5):
        T = s.pert.tensor(j)[0][iA]
        assert T[(a,) * j] == pytest.approx(fall(j), abs=1e-10)
        assert T[(e,) * j] == pytest.approx(sig ** j, abs=1e-12)
        assert T[(a,) * (j - 1) + (e,)] == pytest.approx(fall(j - 1) * sig, abs=1e-10)
    ref = _ref("pert.mat", "o2c")
    r4 = np.asarray(ref.Tzzzz[0], float).reshape((3,) + (4,) * 4)
    assert abs(r4[0, 1, 1, 1, 1] - fall(4)) > 0.1                     # row A, state A(-1) in RISE order


@pytest.mark.parametrize("name,order", [("o2", 5), ("small_nk", 4), ("o2e", 3)])
def test_equation_expansion_vanishes(name, order):
    """Under the full policy, the coefficients of degree 2 to p of the equilibrium conditions are zero."""
    s = _solved(name, order)
    F = equation_residual(s)
    Bz = _Basis(s.pert.nz, order)
    scale = max(1.0, max(np.abs(c).max() for c in s.pert.coef.values()))
    assert np.abs(F[:, :, Bz.off[2]:]).max() < 1e-9 * scale


def _true_residual(s, order, r, z, nodes=9):
    """E[sum_q Q_rq(y_t) f(y_{t+1}, y_t, y_{t-1}, e_t)] with the policy of the given order: equations
    in levels, Gauss-Hermite quadrature and probabilities evaluated at y_t. Does not use the expansion."""
    m = s.model
    stp = _Stepper(s, order, pruned=False)
    k, ne = stp.k, len(m.exogenous)
    x, sg, e = z[:k], z[k], z[k + 1:]

    def policy(reg, xdev, sgm, eta):
        zz = np.concatenate([xdev, [sgm], eta])
        mon = np.zeros(stp.Bz.N)
        mon[0] = 1.0
        for d in range(1, order + 1):
            par, last = stp.parents[d]
            mon[stp.Bz.block(d)] = mon[par] * zz[last]
        return s.ss[reg] + stp.G[reg] @ mon

    y = policy(r, x, sg, e)
    ym = s.ss[r].copy()
    ym[stp.st] += x
    Q = m.transition_matrix(y, y, ym, s.params[r], s.ss[r], regime=r) if m.h > 1 else np.ones(1)
    gx, gw = np.polynomial.hermite_e.hermegauss(nodes)
    gw = gw / gw.sum()
    out = np.zeros(m.n)
    for q in range(m.h):
        for node in np.ndindex(*(nodes,) * ne):
            eps, w = gx[list(node)], np.prod(gw[list(node)])
            yp = policy(q, y[stp.st] - s.ss[q][stp.st], sg, sg * eps)
            out += Q[q] * w * np.asarray(m._f(yp, y, ym, e * s.sigma, s.ss[r], s.params[r]), float).ravel()
    return out


@pytest.mark.parametrize("name,order", [("o2c", 3), ("o2r", 2), ("o2r", 3), ("o2c", 4)])
def test_true_residual_is_of_order_p_plus_1(name, order):
    """Independent check (includes endogenous probabilities, model o2r): along a direction t d of
    the state space, the residual of the equations in levels falls like t^(p+1)."""
    s = _solved(name, order)
    d = np.random.default_rng(0).standard_normal(s.pert.nz) * np.array([1.0, 0.05, 1.0, 1.0])
    big, small = (2.0, 1.0) if order < 4 else (4.0, 2.0)
    for r in range(s.model.h):
        g1 = np.abs(_true_residual(s, order, r, big * d)).max()
        g2 = np.abs(_true_residual(s, order, r, small * d)).max()
        assert g1 / g2 == pytest.approx(2.0 ** (order + 1), rel=0.25)


def test_iterative_solvers_match_direct():
    s = _solved("small_nk", 1)
    ref = solve_perturbation(s, 3, method="kron")
    for method in ("gmres", "tfqmr"):
        p = solve_perturbation(s, 3, method=method)
        assert p.method[3] == method
        for j in (2, 3):
            assert np.abs(p.coef[j] - ref.coef[j]).max() < 1e-9 * np.abs(ref.coef[j]).max()


def test_endogenous_probabilities_second_order_and_limits():
    s = _solved("o2r", 2)
    assert s.G2.shape == (2, 3, 4, 4) and np.isfinite(s.G2).all()
    # the derivatives of the probabilities change the 2nd order relative to a constant Q
    const = _model("o2r")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        s1 = const.solve()
    s1.endogenous_switching = False
    assert np.abs(solve_perturbation(s1, 2).tensor(2) - s.G2).max() > 1e-3
    m = _model("o2")
    with pytest.raises(NotImplementedError):
        m.solve(order=6)
    with pytest.raises(NotImplementedError), warnings.catch_warnings():
        warnings.simplefilter("ignore")
        _model("frwz_nk").solve(order=3, steady_state="unique")


@pytest.mark.parametrize("name", ["o2r", "o2e", "o2x", "o2y", "o2w"])
def test_rise_evaluates_endogenous_probabilities_off_steady_state(name):
    """Record of RISE behaviour: when solving, the endogenous probabilities are evaluated with K
    (a purely predetermined state) at the steady-state value of A. With that, RISE's 1st order is
    reproduced; with Q at the steady state, it is not (except when Q does not depend on K)."""
    ref = _ref("pert2.mat" if name in ("o2x", "o2y", "o2w") else "pert.mat", name)
    m = _model(name)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        right = m.solve(order=2)
    orig, iK, iA = m.transition_matrix, m.endogenous.index("K"), m.endogenous.index("A")

    def bad(y):
        y = np.array(y, float)
        y[iK] = y[iA]
        return y

    m.transition_matrix = lambda yp, y0, ym, pr, ssr, regime=None: orig(bad(yp), bad(y0), bad(ym), pr, ssr, regime=regime)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        s = m.solve()
    pert = solve_perturbation(s, 1)
    mine, rise = _mine_and_rise(m, pert, ref, 1)
    assert np.abs(mine - rise).max() < 1e-6
    mine_right, _ = _mine_and_rise(m, right.pert, ref, 1)
    if name == "o2w":            # probabilities in (A, C): RISE's point coincides with the correct one
        assert np.abs(mine_right - rise).max() < 1e-6
    else:
        assert np.abs(mine_right - rise).max() > 1e-3
    assert s.Q != pytest.approx(np.asarray(ref.Q, float), abs=1e-4) or name == "o2w"   # the Q that RISE reports is the correct one


