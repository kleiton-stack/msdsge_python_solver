def _replay(name, tag, **kw):
    x = getattr(_ref("pert.mat", f"sim_{name}"), tag)
    s = _solved(name, 3)
    m = s.model
    names, data = list(x.names), np.asarray(x.data, float)
    y0 = np.array([data[0, names.index(v)] for v in m.endogenous])
    shocks = np.column_stack([data[1:, names.index(e)] for e in m.exogenous])
    regimes = np.asarray(x.regime, float)[1:].astype(int) if m.h > 1 else None
    df = simulate(s, periods=shocks.shape[0], shocks=shocks, regimes=regimes, order=int(tag[1]), pruned=tag[4] == "1",
                  initial=y0, variables=m.endogenous, **kw)
    return df[m.endogenous].to_numpy(), np.column_stack([data[1:, names.index(v)] for v in m.endogenous]), regimes


@pytest.mark.parametrize("name", ["o2c", "o2", "small_nk"])
@pytest.mark.parametrize("order", [1, 2, 3])
@pytest.mark.parametrize("pruned", [0, 1])
def test_simulation_matches_rise_given_shocks(name, order, pruned):
    """Same shocks, regimes and initial condition as RISE (which returns them in the simulated database)."""
    fix = 1 if name == "small_nk" else 0
    mine, rise, _ = _replay(name, f"o{order}_p{pruned}_r{fix}", regime_switch="rise")
    horizon = 20 if (name, order, pruned) == ("small_nk", 3, 0) else len(rise)   # without pruning the 3rd order of the NK explodes
    assert np.abs(mine - rise)[:horizon].max() < 3e-5 * max(1.0, np.abs(rise[:horizon]).max())


def test_pruned_regime_switch_differs_from_rise_by_design():
    """On a regime change RISE adds the difference between steady states to every pruned
    component; the package adds it only to the 1st-order one. Up to the first change the paths coincide."""
    mine, rise, regimes = _replay("o2", "o2_p1_r0")
    first = int(np.flatnonzero(np.diff(regimes) != 0)[0]) + 1
    assert np.abs(mine - rise)[:first].max() < 1e-5
    assert np.abs(mine - rise)[first].max() > 1.0
    # without pruning there is no ambiguity and the package default matches RISE
    mine, rise, _ = _replay("o2", "o2_p0_r0")
    assert np.abs(mine - rise).max() < 1e-5


def test_solution_simulate_delegates_and_keeps_old_second_order_path():
    """Solution.simulate at 2nd order: the old code (solve.py) and the new one give the same path."""
    s = _solved("o2", 2)
    new = s.simulate(periods=300, seed=3)
    pert, s.pert = s.pert, None
    try:
        old = s.simulate(periods=300, seed=3)
    finally:
        s.pert = pert
    assert (new["regime"] == old["regime"]).all() and new["regime"].nunique() == 2
    assert new.to_numpy() == pytest.approx(old.to_numpy(), abs=1e-9)
    assert s.simulate(periods=50, seed=3, order=1)["regime"].tolist() == new["regime"].tolist()[:50]


def test_pruned_orders_nest_and_first_order_is_linear():
    s = _solved("o2c", 3)
    a = simulate(s, periods=200, seed=5, regimes=[1], order=1)
    b = s.simulate(periods=200, seed=5, regimes=[1], order=1)
    assert a.to_numpy() == pytest.approx(b.to_numpy(), abs=1e-10)
    c = simulate(s, periods=200, seed=5, regimes=[1], order=3)
    d = simulate(s, periods=200, seed=5, regimes=[1], order=3, pruned=False)
    assert 0 < np.abs(c["K"] - d["K"]).max() < 0.5 and np.isfinite(c.to_numpy()).all()


@pytest.mark.parametrize("name", ["o2c", "small_nk"])
def test_irfs_compatible_with_rise(name):
    """At higher order the RISE IRF is a Monte Carlo average (irf_draws=50); the comparison with the
    package's generalised IRF is statistical. The impact in model o2c does not depend on the draws."""
    ref = _ref("pert.mat", f"irf_{name}")
    s = _solved(name, 3)
    shock = ref.shocks if isinstance(ref.shocks, str) else ref.shocks[0]
    g = girf(s, shock, periods=8, draws=300, order=3, regime0=1, seed=1)
    det = irf(s, shock, periods=8, order=3, regime=1)
    for v in ("C", "K"):
        rise = np.asarray(getattr(ref, f"irfp_{v}"), float)
        rise = rise[1:9, 0] if rise.ndim == 2 else rise[1:9]
        scale = np.abs(rise).max()
        assert np.abs(g[v].to_numpy() - rise).max() < 0.05 * scale
        if name == "o2c":      # in the NK the path without future shocks differs from the average with shocks
            assert np.abs(det[v].to_numpy() - rise).max() < 0.05 * scale
            assert det[v].to_numpy()[0] == pytest.approx(rise[0], abs=1e-6)


def test_simulated_moments():
    s = _solved("o2c", 3)
    mom = simulated_moments(s, periods=3000, burn=200, seed=2, order=3)
    assert set(mom) >= {"mean", "std", "skewness", "kurtosis", "autocorr"}
    assert mom["std"]["A"] == pytest.approx(0.02 / np.sqrt(1 - 0.81), rel=0.15)
    assert mom["mean"]["A"] > 1.0                     # Jensen correction absent at 1st order
