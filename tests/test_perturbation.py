import numpy as np
import pytest
import scipy.io as sio

from msdsge import Model
from msdsge.convert import rs_to_mod
from msdsge.perturbation import (_Basis, _Stepper, equation_residual, girf, irf, simulate, simulated_moments,
                                 solve_perturbation)

ROOT = Path(__file__).parents[1]
EX = Path.home() / "RISE_toolbox/examples"
FILES = {
    "small_nk": EX / "Nonlinear3rdOrder/Binning/small_nk.rs",
    "frwz_nk": EX / "MarkovSwitching/FoersterRubioRamirezWaggonerZha/frwz_nk.rs",
}
FIELDS = ["Tz", "Tzz", "Tzzz", "Tzzzz", "Tzzzzz"]
_CACHE = {}


def _file(name):
    return FILES.get(name, ROOT / f"validation/matlab/{name}.rs")


def _model(name):
    path = _file(name)
    if not path.exists():
        pytest.skip(f"model file missing: {path}")
    return Model.from_text(rs_to_mod(path))


def _solved(name, order):
    """Solution cached per (model, order): the symbolic derivatives are the expensive part."""
    if (name, order) not in _CACHE:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            _CACHE[name, order] = _model(name).solve(order=order)
    return _CACHE[name, order]


def _ref(file, key):
    return sio.loadmat(ROOT / "validation/ref" / file, squeeze_me=True, struct_as_record=False)[key]


def _rise_layout(model, pert, ref):
    rows = [model.endogenous.index(v) for v in ref.endo]
    st = [model.endogenous[i] for i in pert.states]
    cols = []
    for name in np.atleast_1d(ref.state_list):
        if name == "@sig":
            cols.append(len(st))
        elif name.endswith("{-1}"):
            cols.append(st.index(name[:-4]))
        else:
            cols.append(len(st) + 1 + model.exogenous.index(name))
    return rows, cols


def _mine_and_rise(model, pert, ref, j):
    rows, cols = _rise_layout(model, pert, ref)
    mine = pert.tensor(j)[:, rows]
    for ax in range(j):
        mine = np.take(mine, cols, axis=2 + ax)
    raw = getattr(ref, FIELDS[j - 1])
    raw = [raw] if model.h == 1 else list(raw)
    rise = np.stack([np.asarray(x, float).reshape(len(rows), -1) for x in raw])
    return mine.reshape(model.h, len(rows), -1), rise


