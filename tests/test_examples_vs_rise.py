"""RISE examples converted and solved by the package, against RISE (validation/ref/examples.mat).

The reference is generated by validation/gen_ref_examples.py: steady state and IRFs per regime
(unit shock, 10 periods). The tests need the .rs files in ~/RISE_toolbox/examples (or $RISE_TOOLBOX/examples).
"""
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).parents[1] / "validation"))
from examples_config import CONFIG, REF, reference          # noqa: E402
from sweep_examples import build, compare, root             # noqa: E402

pytestmark = pytest.mark.skipif(not root.exists() or not REF.exists(), reason="RISE examples or reference missing")

_TZ = "VariousModels/TaoZha/Tutorials/DSGE/"
CASES = [
    # (file, key, ss tolerance, IRF tolerance relative to the scale, what the case exercises)
    ("MarkovSwitching/SmetsWouters/usmodel.rs", "sw_ms", 1e-10, 1e-9),                     # Smets-Wouters, 2 regimes
    (_TZ + "Tutorial2/Models/policyOnly.rs", "tz2_policyOnly", 1e-12, 1e-6),               # parameter_restrictions
    (_TZ + "Tutorial2/Models/volatilityPolicyIndependent.rs", "tz2_volatilityPolicyIndependent", 1e-12, 1e-6),  # 2 chains
    ("MarkovSwitching/GavinKeenRichterThrockmorton/globdynzlb.rs", "globdynzlb", 1e-9, 1e-8),   # parameters in the ss, imposed
    ("Nonlinear3rdOrder/Binning/small_nk.rs", "small_nk", 1e-10, 1e-9),                    # parameter computed in the ss
    ("Nonlinear3rdOrder/Binning/small_nk.rs", "small_nk_log", 1e-10, 1e-9),                # log_vars
    ("NonlinearModels/fs2000.rs", "fs2000_ssfile", 1e-10, 1e-8),                           # Python ss file
    ("NonlinearModels/fs2000_b.rs", "fs2000_b_0", 1e-10, 1e-8),                            # xx_ssmdef_N and macro
    ("ModelsWithSteadyStateFile/Canonical_Const.rs", "canon_ssf", 1e-12, 1e-9),            # Python ss file
    ("VariousModels/PeterIreland/Method_JEDC2004/ireland2004.rs", "ireland2004", 1e-9, 1e-9),   # observed exogenous variable
    ("VariousModels/PeterIreland/NKperspective_JMCB2011/nkp_switch.rs", "nkp_switch", 1e-10, 1e-7),  # parameters from the driver
    ("MarkovSwitching/FoersterRubioRamirezWaggonerZha/QE2016/rbcs.rs", "qe2016_rbcs", 1e-10, 1e-5),  # single point
]


@pytest.mark.parametrize("rel,key,tol_ss,tol_irf", CASES, ids=[c[1] for c in CASES])
def test_example_matches_rise(rel, key, tol_ss, tol_irf):
    cfg = next(c for c in CONFIG[rel] if c["key"] == key)
    ref = reference(key)
    assert ref is not None and ref.retcode == 0
    m, opts = build(rel, cfg)
    s = m.solve(**opts)
    assert s.is_stable == bool(ref.stable)
    # RISE stores the ss in levels; here the log_vars variables are in logs
    dss, dirf, where, scale = compare(s, ref, cfg.get("solve", {}).get("log_vars", ()))
    assert dss < tol_ss
    assert dirf < tol_irf * max(scale, 1.0), where


def test_restrictions_are_converted_and_hold_at_the_calibration():
    rel = _TZ + "Tutorial2/Models/policyOnly.rs"
    m, _ = build(rel, CONFIG[rel][0])
    assert m.spec.restriction_text == ["gamma_1(coef,1)>=gamma_1(coef,2)"]
    assert m.check_restrictions()
    assert not m.check_restrictions(m.parameter_values({"gamma_1": {1: 0.5, 2: 0.77}}))


def test_fs2000_python_steady_state_file_equals_steady_state_model():
    """The hand-ported file gives the same point as the steady_state_model block of fs2000_b.rs."""
    a, oa = build("NonlinearModels/fs2000.rs", CONFIG["NonlinearModels/fs2000.rs"][0])
    b, ob = build("NonlinearModels/fs2000_b.rs", CONFIG["NonlinearModels/fs2000_b.rs"][0])
    sa, sb = a.solve(**oa), b.solve(**ob)
    assert sa.ss == pytest.approx(sb.ss, abs=1e-12)
    assert sa.T == pytest.approx(sb.T, abs=1e-9)
