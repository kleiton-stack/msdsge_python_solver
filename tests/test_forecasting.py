"""Forecast, conditional forecast, counterfactual and remaining items of analysis.py against RISE.

References generated by validation/matlab/ref_tools.m and ref_hdmc.m (RISE commit 1b2edfa).
"""
from pathlib import Path

import numpy as np
import pandas as pd
import pytest
import scipy.io as sio

from msdsge import Model, load
from msdsge.analysis import ergodic_matrices, theoretical_autocorrelations
from msdsge.forecasting import counterfactual, forecast, simulate_path, truncated_mvn
from test_filter import MS

ROOT = Path(__file__).parents[1]
REF = ROOT / "validation" / "ref"
CONST = """var x z; varexo e u; varobs x; parameters a sig; a = 0.9; sig = 0.2;
model; z = a*z(-1) + sig*e; x = z + 0.1*u; end;"""
ORIGIN = 440        # 2100Q1 is observation 441 of a sample that starts in 1990Q1


@pytest.fixture(scope="module")
def ref():
    return sio.loadmat(REF / "tools.mat", squeeze_me=True, struct_as_record=False)


@pytest.fixture(scope="module")
def data():
    return pd.read_csv(REF / "filter_ms_data.csv")


def _case(name):
    return Model.from_text(CONST if name == "tool_c" else MS).solve()


@pytest.mark.parametrize("name", ["tool_c", "flt_ms"])
def test_simulation_with_imposed_regimes_and_shocks_matches_rise(ref, data, name):
    """RISE forecasts (imposed regimes, drawn regimes and with shock uncertainty) redone with the
    regimes and shocks it returns."""
    r, s = ref[name], _case(name)
    f = s.filter(data)
    smo = np.column_stack([f.smoothed_states.to_numpy(), f.smoothed_shocks.to_numpy()])
    assert smo == pytest.approx(r.smo, abs=1e-9)
    for tag in ("fa", "fb", "fc"):
        F = getattr(r, tag)                    # row 0: initial condition; columns x, z, e, u, regime
        assert F[0, :2] == pytest.approx(smo[ORIGIN, :2], abs=1e-9)
        p = simulate_path(s, smo[ORIGIN, :2], F[1:, 2:4], F[1:, 4].astype(int))
        assert p[["x", "z"]].to_numpy() == pytest.approx(F[1:, :2], abs=1e-10)
    # conditional on a shock (Ireland's example): only shock e follows the smoothed history
    fd = r.fd
    p = simulate_path(s, smo[ORIGIN, :2], np.column_stack([smo[ORIGIN + 1:ORIGIN + 9, 2], np.zeros(8)]),
                      fd[1:9, 4].astype(int))
    assert p[["x", "z"]].to_numpy() == pytest.approx(fd[1:9, :2], abs=1e-10)


@pytest.mark.parametrize("name", ["tool_c", "flt_ms"])
def test_conditional_forecast_matches_rise(ref, data, name):
    r, s = ref[name], _case(name)
    h = s.T.shape[0]
    y0, fut = r.smo[ORIGIN, :2], r.smo[ORIGIN + 1:ORIGIN + 9]
    origin = (y0, np.eye(h)[0])
    reg = r.fe[1:, 4].astype(int)
    # condition on the endogenous x: minimum-norm shocks
    fc = forecast(s, origin, steps=8, regimes=reg, shock_uncertainty=False, cond_endo={"x": fut[:, 0]})
    assert fc.mean[["x", "z"]].to_numpy() == pytest.approx(r.fe[1:, :2], abs=1e-9)
    assert fc.shocks.to_numpy() == pytest.approx(r.fe[1:, 2:4], abs=1e-8)
    # the RISE hypotheses coincide when there are no anticipated shocks
    for hyp in ("jma", "ncp", "nas"):
        assert getattr(r, f"fe_{hyp}") == pytest.approx(r.fe, abs=1e-12, nan_ok=True)
    # condition on x and on shock u at the same time
    fc = forecast(s, origin, steps=8, regimes=reg, shock_uncertainty=False,
                  cond_endo={"x": fut[:, 0]}, cond_exo={"u": fut[:, 3]})
    assert fc.mean[["x", "z"]].to_numpy() == pytest.approx(r.ff[1:, :2], abs=1e-9)
    assert fc.shocks.to_numpy() == pytest.approx(r.ff[1:, 2:4], abs=1e-8)
    # with shock uncertainty the condition still holds in every draw
    fc = forecast(s, origin, steps=8, regimes=reg, draws=200, cond_endo={"x": fut[:, 0]}, seed=1)
    kx = fc.variables.index("x")
    assert np.abs(fc.draws[:, :, kx] - fut[:, 0]).max() < 1e-9
    assert fc.draws[:, :, fc.variables.index("z")].std(0).min() > 1e-3
    # the RISE draw (fg) meets the condition and is a solution of the same linear system
    p = simulate_path(s, y0, r.fg[1:, 2:4], reg)
    assert p["x"].to_numpy() == pytest.approx(fut[:, 0], abs=1e-9)


def test_conditional_forecast_with_regime_specific_steady_state(ref):
    r = ref["refA"]
    s = load(ROOT / "examples" / "refA.mod").solve()
    f = s.filter(pd.read_csv(REF / "refA_data.csv"))
    smo = np.column_stack([f.smoothed_states.to_numpy(), f.smoothed_shocks.to_numpy()])
    assert smo == pytest.approx(r.smo, abs=1e-6)
    o = 39                                           # 1999Q4
    reg = r.fa[1:, 3].astype(int)
    p = simulate_path(s, r.smo[o, :2], np.zeros((6, 1)), reg)
    assert p[["X", "Z"]].to_numpy() == pytest.approx(r.fa[1:, :2], abs=1e-6)
    fc = forecast(s, (r.smo[o, :2], [1.0, 0.0]), steps=6, regimes=reg, shock_uncertainty=False,
                  cond_endo={"Z": r.smo[o + 1:o + 7, 1]})
    assert fc.mean[["X", "Z"]].to_numpy() == pytest.approx(r.fe[1:, :2], abs=1e-6)
    assert fc.shocks["E"].to_numpy() == pytest.approx(r.fe[1:, 2], abs=1e-5)


def test_unconditional_forecast_bands_and_regime_uncertainty(data):
    s = Model.from_text(MS).solve()
    f = s.filter(data)
    # without shock uncertainty the simulation mean tends to the analytical point forecast
    fc = forecast(s, f, steps=8, draws=4000, shock_uncertainty=False, seed=2)
    point = s.forecast(f, steps=8)
    assert fc.mean["z"].to_numpy() == pytest.approx(point["z"].to_numpy(), abs=0.03)
    assert fc.regime_probs["regime_1"].to_numpy() == pytest.approx(point["prob_regime_1"].to_numpy(), abs=0.03)
    # with shocks: ordered bands and variance consistent with the theoretical one in the single regime
    sc = Model.from_text(CONST).solve()
    fcc = forecast(sc, sc.filter(data), steps=6, draws=4000, seed=3)
    q = fcc.quantiles
    assert np.all(q.loc[0.05].to_numpy() <= q.loc[0.5].to_numpy()) and np.all(q.loc[0.5].to_numpy() <= q.loc[0.95].to_numpy())
    var_z = np.cumsum(0.04 * 0.81 ** np.arange(6))
    assert fcc.draws[:, :, fcc.variables.index("z")].var(0) == pytest.approx(var_z, rel=0.1)
    b = fcc.band("z")
    assert np.all(b["lower"] < b["mean"]) and np.all(b["mean"] < b["upper"])
    # start in the middle of the sample: starts from the smoothed state of the previous period
    f2 = forecast(sc, sc.filter(data), steps=3, shock_uncertainty=False, start=100)
    zs = sc.filter(data).smoothed_states["z"].to_numpy()
    assert f2.mean["z"].to_numpy() == pytest.approx(zs[99] * 0.9 ** np.arange(1, 4))
    assert list(f2.mean.index) == [100, 101, 102]


def test_soft_conditions_and_free_shocks():
    s = Model.from_text(CONST).solve()
    y0 = np.zeros(2)
    # interval that the unconditional forecast (zero) violates: all draws stay inside
    for algo in ("rejection", "gibbs"):
        fc = forecast(s, y0, steps=4, draws=300, cond_lower={"z": [0.1, 0.1]}, cond_upper={"z": [0.3, 0.3]},
                      sampling_algo=algo, seed=4)
        z = fc.draws[:, :2, fc.variables.index("z")]
        assert z.min() >= 0.1 - 1e-9 and z.max() <= 0.3 + 1e-9
        assert z.std() > 0.01
    # only shock u can adjust: z does not change and x is hit by u
    fc = forecast(s, y0, steps=2, shock_uncertainty=False, cond_endo={"x": [0.5, 0.2]}, free_shocks=["u"])
    assert fc.mean["z"].abs().max() < 1e-12 and fc.shocks["u"].to_numpy() == pytest.approx([5.0, 2.0])
    with pytest.raises(ValueError, match="cannot be met"):
        forecast(s, y0, steps=2, shock_uncertainty=False, cond_endo={"z": [0.5, 0.2]}, free_shocks=["u"])
    rng = np.random.default_rng(0)
    x = np.array([truncated_mvn([0, 0], [[1, 0.5], [0.5, 1]], [1, -np.inf], [np.inf, 0], rng, "gibbs", 20)
                  for _ in range(200)])
    assert x[:, 0].min() >= 1 and x[:, 1].max() <= 0


def test_anticipated_conditional_forecast_uses_future_shocks():
    m = load(ROOT / "examples" / "refA.mod")
    s = m.solve(shock_horizon=2)
    y0 = s.ss[0]
    fc = forecast(s, (y0, [1.0, 0.0]), steps=5, regimes=1, shock_uncertainty=False, anticipated=True,
                  cond_endo={"X": [np.nan, np.nan, 1.5]})
    assert fc.mean["X"].iloc[2] == pytest.approx(1.5)
    # Z is forward-looking: with the shocks known in advance, it reacts in period 1 to what is coming
    naive = simulate_path(s, y0, fc.shocks, 1, anticipated=False)
    assert naive["X"].to_numpy() == pytest.approx(fc.mean["X"].to_numpy())
    assert abs(naive["Z"].iloc[0] - fc.mean["Z"].iloc[0]) > 1e-3
    p = simulate_path(s, y0, fc.shocks, 1, anticipated=True)
    assert p[["X", "Z"]].to_numpy() == pytest.approx(fc.mean[["X", "Z"]].to_numpy())
    with pytest.raises(ValueError, match="shock_horizon"):
        forecast(m.solve(), (y0, [1.0, 0.0]), steps=3, anticipated=True)


def test_counterfactual(data):
    sc = Model.from_text(CONST).solve()
    f = sc.filter(data)
    # one regime and all the shocks: reproduces the smoothed history
    assert counterfactual(sc, f).to_numpy() == pytest.approx(f.smoothed_states.to_numpy(), abs=1e-9)
    # without shock u, x = z; and the sum with the historical decomposition adds up
    cf = counterfactual(sc, f, shocks=["e"])
    assert cf["x"].to_numpy()[1:] == pytest.approx(cf["z"].to_numpy()[1:], abs=1e-12)
    hd = sc.historical_decomposition(f)
    assert cf["x"].to_numpy()[1:] == pytest.approx((hd["x"]["e"] + hd["x"]["init"]).to_numpy()[1:], abs=1e-9)
    # another policy with the same shocks
    alt = Model.from_text(CONST.replace("a = 0.9", "a = 0.5")).solve()
    assert counterfactual(sc, f, alt_solution=alt)["z"].std() < f.smoothed_states["z"].std()
    # with regime switching: most likely regime or mean of drawn paths
    s = Model.from_text(MS).solve()
    f2 = s.filter(data.iloc[:120])
    a, b = counterfactual(s, f2), counterfactual(s, f2, regimes="draws", draws=50)
    assert np.corrcoef(a["z"], f2.smoothed_states["z"])[0, 1] > 0.95
    assert np.isfinite(b.to_numpy()).all()
    assert counterfactual(s, f2, regimes=1)["z"].iloc[1] == pytest.approx(
        0.9 * f2.smoothed_states["z"].iloc[0] + 0.2 * f2.smoothed_shocks["e"].iloc[1])


