def test_autocovariances_rule_of_rise(ref):
    """RISE uses the average T and R under the ergodic distribution; ac[:, :, k] = Tbar^k V."""
    s = Model.from_text(MS).solve()
    assert s.theoretical_autocovariances(lags=3) == pytest.approx(ref["flt_ms"].ac, abs=1e-10)
    assert theoretical_autocorrelations(s, lags=5) == pytest.approx(ref["flt_ms"].acorr, abs=1e-10)
    sc = Model.from_text(CONST).solve()
    assert sc.theoretical_autocovariances(lags=3) == pytest.approx(ref["tool_c"].ac, abs=1e-10)
    assert sc.theoretical_autocovariances(lags=3, regime=1) == pytest.approx(ref["tool_c"].ac, abs=1e-10)
    sa = load(ROOT / "examples" / "refA.mod").solve()
    assert sa.theoretical_autocovariances(lags=2) == pytest.approx(ref["refA"].ac, abs=1e-8)
    T, _ = ergodic_matrices(s)
    assert T[1, 1] == pytest.approx(0.9 * 2 / 3 + 0.1 / 3)




def test_ergodic_and_simulated_variance_decomposition(ref):
    s = Model.from_text(MS).solve()
    r = ref["flt_ms"]
    vd = s.variance_decomposition(ergodic=True, periods=tuple(range(1, 401)))["ergodic"]
    for v in ("x", "z"):
        assert vd.loc[v].iloc[:400].to_numpy() == pytest.approx(getattr(r, f"vde_cond_{v}"), abs=1e-10)
        assert vd.loc[v].loc[np.inf].to_numpy() == pytest.approx(getattr(r, f"vde_inf_{v}"), abs=1e-10)
    # simulated, stuck in one regime: converges to the theoretical one of the regime
    sim = s.variance_decomposition(theoretical=False, regime=1, periods=(1, 4, 40), draws=20000, seed=1)[1]
    th = s.variance_decomposition(regime=1, periods=(1, 4, 40))[1]
    assert sim.to_numpy() == pytest.approx(th.to_numpy(), abs=0.01)
    # simulated with switching: fractions sum to one; differs from RISE's average-matrix rule
    erg = s.variance_decomposition(theoretical=False, periods=(1, 4))["ergodic"]
    assert erg.sum(axis=1).to_numpy() == pytest.approx(1.0)
    assert erg.loc[("z", 1), "e"] == pytest.approx(1.0)
    # horizon 1 exact: E[R_s^2] under the ergodic distribution
    share = (2 / 3 * 0.04 + 1 / 3 * 2.25) / (2 / 3 * 0.04 + 1 / 3 * 2.25 + 0.01)
    assert erg.loc[("x", 1), "e"] == pytest.approx(share, abs=0.01)


def test_historical_decomposition_single_regime_matches_rise(ref, data):
    s = Model.from_text(CONST).solve()
    f = s.filter(data)
    for method in ("weighted", "rise"):
        hd = s.historical_decomposition(f, method=method)
