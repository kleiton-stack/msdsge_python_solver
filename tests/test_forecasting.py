def test_historical_decomposition_rise_rule_with_switching(data):
    """RISE's decomposition with switching is Monte Carlo (100 simulations); method='rise' with
    draws=None gives the exact expectation. Comparison with the mean of 300 RISE calls."""
    d = sio.loadmat(REF / "hdmc.mat", squeeze_me=True)
    s = Model.from_text(MS).solve()
    f = s.filter(data.iloc[:60])
    hd = s.historical_decomposition(f, method="rise")
    mine = hd["z"][["e", "u", "init"]].to_numpy()
    se = d["hdmc_z_std"] / np.sqrt(300)
    assert np.abs(mine - d["hdmc_z_mean"]).max(0) == pytest.approx(0, abs=0.01)
    assert np.all(np.abs(mine - d["hdmc_z_mean"]) <= 4.5 * se + 1e-6)
    assert hd["x"][["e", "u", "init"]].to_numpy() == pytest.approx(d["hdmc_x_mean"], abs=0.01)
    # RISE is not reproducible across calls: two of the stored calls differ
    assert np.abs(d["hdmc_z_first"][:, :, 0] - d["hdmc_z_first"][:, :, 1]).max() > 0.01
    # the rule attributes to u part of z, which does not depend on u; the default rule does not
    assert hd["z"]["u"].abs().max() > 0.1
    assert s.historical_decomposition(f)["z"]["u"].abs().max() < 1e-12
    # the simulated version (like RISE) is close to the expectation and sums to the smoothed variable
    mc = s.historical_decomposition(f, method="rise", draws=100, seed=1)
    assert mc["z"]["e"].to_numpy() == pytest.approx(hd["z"]["e"].to_numpy(), abs=0.02)
    assert mc["z"].sum(axis=1).to_numpy() == pytest.approx(f.smoothed_states["z"].to_numpy(), abs=1e-10)
