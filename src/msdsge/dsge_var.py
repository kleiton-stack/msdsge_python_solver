"""DSGE-VAR (Del Negro and Schorfheide, 2004): VAR with a prior centred on the restrictions of a DSGE.

The VAR of the observables, ``y_t = Phi' x_t + u_t`` with ``x_t = [1, y_{t-1}, ..., y_{t-p}]``, gets
a conjugate prior formed by ``lambda T`` dummy observations generated by the DSGE. Instead of
simulating, the population moments of the solved model (``Solution``) are used: with
``Gamma*_XX = E[x x']``, ``Gamma*_XY = E[x y']`` and ``Gamma*_YY = E[y y']``,

    Phi*   = Gamma*_XX^{-1} Gamma*_XY,          Sigma* = Gamma*_YY - Gamma*_YX Gamma*_XX^{-1} Gamma*_XY,

and the marginal likelihood of ``Y`` given theta and lambda has a closed form (equation A.2 of the
paper). A large ``lambda`` imposes the DSGE restrictions; a small ``lambda`` approaches the
unrestricted VAR.

In RISE the model becomes a DSGE-VAR when it declares the parameter ``dsge_prior_weight`` (options
``dsgevar_lag`` and ``dsgevar_constant``); the same convention applies here, or the fixed weight
``lam``. In the local copy of RISE the feature does not run (``solve`` and ``estimate`` end in an
error), so validation is against the analytical properties of the method (see
``tests/test_dsge_var.py``).
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd
from scipy import special

from .analysis import theoretical_autocovariances
from .estimation import EstimationProblem
from .model import SteadyStateError
from .solve import SolveError
from .var import VAR, VARResults, gaussian_loglik

WEIGHT_PARAMETER = "dsge_prior_weight"


def dsge_moments(solution, nlags: int = 4, constant: bool = True, regime: int = 1, observables=None):
    """Population moments of the observables implied by the solved DSGE.

    Returns ``(GYY, GXY, GXX)`` with ``x_t = [1, y_{t-1}, ..., y_{t-p}]`` (without the 1 if
    ``constant=False``; in that case the moments are those of the variables in deviation from the
    mean). With regime switching, the moments are those of the given regime, conditional on staying
    in it.
    """
    m = solution.model
    obs = list(m.spec.observables) if observables is None else list(observables)
    if not obs:
        raise ValueError("the model declares no observables (varobs)")
    idx = [m.endogenous.index(v) for v in obs]
    n, p, r = len(idx), nlags, regime - 1
    G = theoretical_autocovariances(solution, lags=p, regime=regime)[np.ix_(idx, idx)]     # (n, n, p+1)
    mu = np.zeros(n)
    if constant:
        T = solution.T[r]
        full = solution.ss[r] + np.linalg.solve(np.eye(T.shape[0]) - T, solution.c[r])
        mu = full[idx]
    mm = np.outer(mu, mu)

    def second(k):          # E[y_t y_{t-k}']
        return (G[:, :, k] if k >= 0 else G[:, :, -k].T) + mm
    nd = 1 if constant else 0
    K = nd + n * p
    GYY = second(0)
    GXY = np.zeros((K, n))
    GXX = np.zeros((K, K))
    if constant:
        GXX[0, 0] = 1.0
        GXY[0] = mu
    for i in range(1, p + 1):
        si = slice(nd + (i - 1) * n, nd + i * n)
        GXY[si] = second(i).T                 # E[y_{t-i} y_t']
        if constant:
            GXX[0, si] = GXX[si, 0] = mu
        for j in range(1, p + 1):
            sj = slice(nd + (j - 1) * n, nd + j * n)
            GXX[si, sj] = second(j - i)       # E[y_{t-i} y_{t-j}']
    return GYY, GXY, (GXX + GXX.T) / 2


def dsge_var_restrictions(GYY, GXY, GXX):
    """VAR coefficients and covariance implied by the DSGE: ``(Phi*, Sigma*)`` with Phi* n x K."""
    Phi = np.linalg.solve(GXX, GXY)
    Sig = GYY - GXY.T @ Phi
    return Phi.T, (Sig + Sig.T) / 2


def _logdet(A):
    sign, ld = np.linalg.slogdet(A)
    return ld if sign > 0 else -np.inf


def dsge_var_loglik(Y: np.ndarray, X: np.ndarray, GYY, GXY, GXX, lam: float):
    """Log marginal likelihood ``p(Y | theta, lambda)`` of Del Negro and Schorfheide (2004).

    Returns ``(loglik, Phi, Sigma)``: posterior mean of the coefficients (n x K) and the matrix
    ``Sigma~`` (mode of the concentrated likelihood). With ``lam = inf`` it is the Gaussian
    likelihood of the VAR at the parameters ``(Phi*, Sigma*)``. Requires ``lam T > K + n`` (proper prior).
    """
    T, n = Y.shape
    K = X.shape[1]
    if np.isinf(lam):
        Phi, Sig = dsge_var_restrictions(GYY, GXY, GXX)
        return gaussian_loglik(Y - X @ Phi.T, Sig), Phi, Sig
    if lam * T <= K + n:
        raise ValueError(f"lambda must be larger than (K + n)/T = {(K + n) / T:.4f} for the prior to be proper")
    lT = lam * T
    XX, XY, YY = X.T @ X, X.T @ Y, Y.T @ Y
    Axx = lT * GXX + XX
    Phi = np.linalg.solve(Axx, lT * GXY + XY)
    Sig = ((lT * GYY + YY) - (lT * GXY + XY).T @ Phi) / ((1 + lam) * T)
    Sig = (Sig + Sig.T) / 2
    Phi_star = np.linalg.solve(GXX, GXY)
    Sig_star = GYY - GXY.T @ Phi_star
    d1, d0 = (1 + lam) * T - K, lT - K
    ll = (-0.5 * n * (_logdet(Axx) - _logdet(lT * GXX))
          - 0.5 * d1 * _logdet((1 + lam) * T * Sig) + 0.5 * d0 * _logdet(lT * Sig_star)
          - 0.5 * n * T * np.log(np.pi)
          + special.multigammaln(0.5 * d1, n) - special.multigammaln(0.5 * d0, n))
    return (float(ll) if np.isfinite(ll) else -np.inf), Phi.T, Sig


def _observables(model):
    obs = list(model.spec.observables)
    if not obs:
        raise ValueError("the model declares no observables (varobs)")
    return obs


def _weight(solution, lam):
    names = solution.model.parameters
    if WEIGHT_PARAMETER in names:
        return float(solution.params[0, names.index(WEIGHT_PARAMETER)])
    if lam is None:
        raise ValueError(f"pass 'lam' or declare the parameter {WEIGHT_PARAMETER} in the model")
    return float(lam)


@dataclass
class DSGEVAR:
    """DSGE-VAR evaluated at a DSGE solution: likelihood, posterior of (Phi, Sigma) and analyses."""
    solution: object
    var: VAR
    data: object            # VARData
    lam: float
    regime: int
    loglik: float
    Phi: np.ndarray         # (n, K) posterior mean
    Sigma: np.ndarray
    Phi_dsge: np.ndarray    # DSGE restrictions
    Sigma_dsge: np.ndarray
    moments: tuple

    def to_var(self) -> VARResults:
        """VAR result with (Phi, Sigma) of the DSGE-VAR, for IRF, decompositions and forecast."""
        v, n = self.var, self.var.n
        theta = v.layout.pack(np.eye(n)[None], self.Phi[None], self.Sigma[None])
        U = self.data.Y - self.data.X @ self.Phi.T
        return VARResults(model=v, data=self.data, theta=theta, A0=np.eye(n)[None], Bs=self.Phi[None],
                          Sigmas=self.Sigma[None], Q=np.ones((1, 1)), loglik=gaussian_loglik(U, self.Sigma),
                          method="dsge-var")

    def rotation(self) -> np.ndarray:
        """Rotation ``Omega*`` of the DSGE: the impact of the shocks on the observables is ``chol(Sigma*) Omega*``."""
        s, m = self.solution, self.solution.model
        idx = [m.endogenous.index(v) for v in self.var.endog]
        A = (s.R[self.regime - 1] * s.sigma)[idx]              # n x n_exo
        Qm, Rm = np.linalg.qr(A.T, mode="complete")           # A' = Q R  ->  A = R' Q'
        Lt = Rm[:A.shape[0]].T                                # lower triangular
        sg = np.sign(np.diag(Lt))
        sg[sg == 0] = 1.0
        return (Qm[:, :A.shape[0]] * sg).T                    # n x n_exo, with Omega Omega' = I

    def impact(self) -> pd.DataFrame:
        """Impact of the DSGE structural shocks in the DSGE-VAR: ``chol(Sigma~) Omega*``
        (Del Negro and Schorfheide, 2004, section 5). Columns: DSGE shocks."""
        R = np.linalg.cholesky(self.Sigma) @ self.rotation()
        return pd.DataFrame(R, index=self.var.endog, columns=self.solution.model.exogenous)

    def irf(self, periods: int = 40) -> pd.DataFrame:
        """IRFs of the DSGE-VAR to the DSGE shocks. Index (shock, period)."""
        from .var import ma_coefficients
        v = self.var
        R = self.impact().to_numpy()
        Th = ma_coefficients(self.Phi[:, v.nd:], v.n, v.nlags, periods)
        rows, keys = [], []
        for k, s in enumerate(self.solution.model.exogenous):
            for t in range(periods):
                rows.append(Th[t] @ R[:, k])
                keys.append((s, t))
        return pd.DataFrame(rows, columns=v.endog, index=pd.MultiIndex.from_tuples(keys, names=["shock", "period"]))

    def sample_posterior(self, draws: int = 1000, seed: int = 0) -> list:
        """Draws of (Phi, Sigma) | Y, theta: Sigma ~ IW((1+lambda) T Sigma~, (1+lambda) T - K) and
        Phi | Sigma ~ N(Phi~, Sigma (x) (lambda T Gamma*_XX + X'X)^{-1})."""
        from scipy import stats
        if np.isinf(self.lam):
            return [(self.Phi.copy(), self.Sigma.copy()) for _ in range(draws)]
        rng = np.random.default_rng(seed)
        T, n = self.data.Y.shape
        K = self.data.X.shape[1]
        Axx = self.lam * T * self.moments[2] + self.data.X.T @ self.data.X
        Lp = np.linalg.cholesky(np.linalg.inv(Axx))
        out = []
        for _ in range(draws):
            Sig = np.atleast_2d(stats.invwishart.rvs(df=(1 + self.lam) * T - K, scale=(1 + self.lam) * T * self.Sigma, random_state=rng))
            out.append((self.Phi + np.linalg.cholesky(Sig) @ rng.standard_normal((n, K)) @ Lp.T, Sig))
        return out


def dsge_var(solution, data: pd.DataFrame, nlags: int = 4, lam: float | None = None, constant: bool = True,
             regime: int = 1, sample=None) -> DSGEVAR:
    """Build the DSGE-VAR of the model's observables at a given solution.

    ``lam`` is the prior weight (``np.inf`` imposes the DSGE); if the model declares the parameter
    ``dsge_prior_weight``, the value comes from it. The first ``nlags`` observations are the
    initial condition.
    """
    obs = _observables(solution.model)
    v = VAR(obs, nlags=nlags, constant=constant)
    d = v.make_data(data, sample)
    lam = _weight(solution, lam)
    mom = dsge_moments(solution, nlags, constant, regime, obs)
    ll, Phi, Sig = dsge_var_loglik(d.Y, d.X, *mom, lam)
    Phi_s, Sig_s = dsge_var_restrictions(*mom)
    return DSGEVAR(solution=solution, var=v, data=d, lam=lam, regime=regime, loglik=ll, Phi=Phi, Sigma=Sig,
                   Phi_dsge=Phi_s, Sigma_dsge=Sig_s, moments=mom)


class DSGEVARProblem(EstimationProblem):
    """Joint estimation problem for theta (and lambda, if ``dsge_prior_weight`` is in
    ``estimated_params``) with the DSGE-VAR likelihood in place of the Kalman filter one.

    Options beyond those of ``EstimationProblem``: ``nlags`` (default 4, RISE's ``dsgevar_lag``),
    ``lam``, ``constant`` (``dsgevar_constant``) and ``regime``.
    """

    def __init__(self, model, data: pd.DataFrame, nlags: int = 4, lam: float | None = None, constant: bool = True,
                 regime: int = 1, **options):
        super().__init__(model, data, **options)
        self.nlags, self.lam, self.constant, self.regime = nlags, lam, constant, regime
        self.observables = _observables(model)
        self.var = VAR(self.observables, nlags=nlags, constant=constant)
        self.var_data = self.var.make_data(data)
        if lam is None and WEIGHT_PARAMETER not in model.parameters:
            raise ValueError(f"pass 'lam' or declare the parameter {WEIGHT_PARAMETER} in the model")

    def dsge_var(self, theta) -> DSGEVAR:
        sol = self.solve(np.asarray(theta, float))
        lam = _weight(sol, self.lam)
        mom = dsge_moments(sol, self.nlags, self.constant, self.regime, self.observables)
        d = self.var_data
        ll, Phi, Sig = dsge_var_loglik(d.Y, d.X, *mom, lam)
        Phi_s, Sig_s = dsge_var_restrictions(*mom)
        return DSGEVAR(solution=sol, var=self.var, data=d, lam=lam, regime=self.regime, loglik=ll, Phi=Phi,
                       Sigma=Sig, Phi_dsge=Phi_s, Sigma_dsge=Sig_s, moments=mom)

    def loglik(self, theta) -> float:
        theta = np.asarray(theta, float)
        if np.any(theta < self.lower) or np.any(theta > self.upper) or not np.all(np.isfinite(theta)):
            return -np.inf
        try:
            sol = self.solve(theta)
            if self.check_stability and not sol.is_stable:
                return -np.inf
            lam = _weight(sol, self.lam)
            mom = dsge_moments(sol, self.nlags, self.constant, self.regime, self.observables)
            ll = dsge_var_loglik(self.var_data.Y, self.var_data.X, *mom, lam)[0]
        except (SolveError, SteadyStateError, ValueError, np.linalg.LinAlgError, FloatingPointError):
            return -np.inf
        return ll if np.isfinite(ll) else -np.inf


def estimate_dsge_var(model, data: pd.DataFrame, nlags: int = 4, lam: float | None = None, constant: bool = True,
                      regime: int = 1, **options):
    """Posterior mode of theta (and lambda) with the DSGE-VAR likelihood.

    Shortcut for ``estimation.estimate(model, data, problem_class=DSGEVARProblem, ...)``; the
    result is an ordinary ``EstimationResult`` (usable with ``mcmc``), and
    ``result.problem.dsge_var(result.mode)`` returns the DSGE-VAR at the mode.
    """
    from .estimation import estimate
    return estimate(model, data, problem_class=DSGEVARProblem, nlags=nlags, lam=lam, constant=constant,
                    regime=regime, **options)
